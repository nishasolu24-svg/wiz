/**
 * Matches a user query or question text to relevant curated educational diagrams.
 */
export function findMatchingDiagrams(query: string): FreeImageResult[] {
  if (!query || !query.trim()) {
    return EDUCATIONAL_DIAGRAMS;
  }
  const clean = query.toLowerCase().trim();

  // Keyword associations
  const keywords: Record<string, string[]> = {
    'diag-digestive-full': ['digestive', 'digestion', 'digestive system', 'organ', 'gut', 'alimentary', 'mouth', 'esophagus', 'pharynx'],
    'diag-digestive-unlabeled': ['digestive', 'identification', 'identify', 'label', 'parts', 'digestive parts', 'organs'],
    'diag-stomach': ['stomach', 'gastric', 'acid', 'pepsin', 'chyme'],
    'diag-liver-gallbladder': ['liver', 'gallbladder', 'pancreas', 'bile', 'insulin', 'hepatic'],
    'diag-small-intestine': ['intestine', 'small intestine', 'large intestine', 'colon', 'duodenum', 'villi'],
    'diag-heart': ['heart', 'cardiac', 'circulatory', 'ventricle', 'atrium', 'blood', 'artery', 'vein'],
    'diag-respiratory': ['lung', 'respiratory', 'trachea', 'bronchi', 'alveoli', 'oxygen', 'breathing'],
    'diag-skeleton': ['skeleton', 'bone', 'skeletal', 'skull', 'femur', 'ribs'],
    'diag-brain': ['brain', 'nervous', 'cerebrum', 'cerebellum', 'lobe', 'neuron'],
    'diag-plant-cell': ['plant cell', 'chloroplast', 'cell wall', 'vacuole', 'photosynthesis'],
    'diag-animal-cell': ['animal cell', 'cell', 'mitochondria', 'organelle', 'nucleus', 'membrane'],
    'diag-photosynthesis': ['photosynthesis', 'chlorophyll', 'light', 'glucose', 'sunlight'],
    'diag-flower-anatomy': ['flower', 'petal', 'stamen', 'pistil', 'pollen', 'anther'],
    'diag-solar-system': ['solar system', 'planet', 'planets', 'sun', 'mercury', 'venus', 'earth', 'mars', 'jupiter'],
    'diag-water-cycle': ['water cycle', 'evaporation', 'condensation', 'precipitation', 'rain', 'runoff'],
    'diag-moon-phases': ['moon', 'lunar', 'phase', 'full moon', 'crescent'],
    'diag-earth-layers': ['earth', 'crust', 'mantle', 'core', 'geology'],
    'diag-bohr-atom': ['atom', 'bohr', 'electron', 'proton', 'neutron', 'atomic'],
    'diag-electric-circuit': ['circuit', 'electric', 'voltage', 'current', 'switch', 'battery'],
    'diag-world-map': ['map', 'continent', 'world', 'geography', 'ocean'],
    'diag-compass-rose': ['compass', 'direction', 'north', 'south', 'east', 'west'],
    'diag-geometric-shapes': ['geometry', 'shape', 'triangle', 'polygon', 'angle'],
    'diag-cartesian-plane': ['coordinate', 'cartesian', 'graph', 'quadrant', 'grid', 'x-axis'],
  };

  const results = EDUCATIONAL_DIAGRAMS.filter((diagram) => {
    // Check title, caption, category
    if (
      diagram.title.toLowerCase().includes(clean) ||
      diagram.caption.toLowerCase().includes(clean) ||
      diagram.category.toLowerCase().includes(clean)
    ) {
      return true;
    }

    // Check keyword map
    const customKeys = keywords[diagram.id];
    if (customKeys) {
      return customKeys.some((k) => clean.includes(k) || k.includes(clean));
    }
    return false;
  });

  return results;
}
